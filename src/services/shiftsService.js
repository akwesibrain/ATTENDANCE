function readShifts() {
  try {
    const stored = window.localStorage.getItem(SHIFTS_KEY)
    if (stored) return JSON.parse(stored)
  } catch {
    // fall through to seed
  }
  // First run: seed and persist.
  writeShifts(SEED_SHIFTS)
  return SEED_SHIFTS.slice()
}

function writeShifts(shifts) {
  try {
    window.localStorage.setItem(SHIFTS_KEY, JSON.stringify(shifts))
  } catch {
    // Ignore — mock persistence only.
  }
}

/* --------------------------------------------------------------------------
 * Time helpers
 * ------------------------------------------------------------------------ */

/** "HH:MM" -> minutes since midnight. */
export function timeToMinutes(time) {
  const [h, m] = (time ?? '0:0').split(':').map(Number)
  return h * 60 + (m || 0)
}

/** Minutes since midnight -> "HH:MM". */
export function minutesToTime(minutes) {
  const normalized = ((minutes % 1440) + 1440) % 1440
  const h = Math.floor(normalized / 60)
  const m = normalized % 60
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`
}

/** Whether a shift crosses midnight (end earlier than or equal to start). */
export function isOvernight(shift) {
  return timeToMinutes(shift.endTime) <= timeToMinutes(shift.startTime)
}

/** The shift's working window in minutes, accounting for overnight shifts. */
export function shiftWindowMinutes(shift) {
  const start = timeToMinutes(shift.startTime)
  let end = timeToMinutes(shift.endTime)
  if (end <= start) end += 1440 // overnight: end is next day
  return { start, end, span: end - start }
}

/** "HH:MM" (24h) -> "6:00 AM" for display. */
export function formatClock(time) {
  if (!time) return '—'
  const minutes = timeToMinutes(time)
  return new Date(2000, 0, 1, Math.floor(minutes / 60), minutes % 60).toLocaleTimeString([], {
    hour: 'numeric',
    minute: '2-digit',
  })
}

/** Expected working hours derived from the window minus the break. */
export function expectedWorkingHours(shift) {
  const { span } = shiftWindowMinutes(shift)
  const breakMinutes = Math.max(
    0,
    timeToMinutes(shift.breakEnd) - timeToMinutes(shift.breakStart),
  )
  return Math.round(((span - breakMinutes) / 60) * 10) / 10
}

/** Human-readable working days, e.g. "Monday to Friday" or "Mon, Wed, Fri". */
export function formatWorkingDays(days) {
  if (!Array.isArray(days) || days.length === 0) return '—'
  const sorted = days.slice().sort((a, b) => a - b)
  // Consecutive run (e.g. Mon–Fri)
  const isConsecutive = sorted.every((d, i) => i === 0 || d === sorted[i - 1] + 1)
  if (isConsecutive && sorted.length > 1) {
    return `${DAY_NAMES[sorted[0]]} to ${DAY_NAMES[sorted[sorted.length - 1]]}`
  }
  return sorted.map((d) => DAY_NAMES[d].slice(0, 3)).join(', ')
}

