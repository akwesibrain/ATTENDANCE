export function mockListShifts(companyId) {
  const shifts = readShifts()
  return companyId ? shifts.filter((s) => s.companyId === companyId) : shifts
}

export function mockGetShift(shiftId) {
  return readShifts().find((s) => s.shiftId === shiftId) ?? null
}

function generateShiftId(name) {
  const slug = (name ?? 'shift')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
  return `shift-${slug}-${Date.now().toString(36)}`
}

/** Whether another shift in the same company already uses this code. */
function isDuplicateCode(shifts, data, ignoreShiftId) {
  const code = data.code?.trim().toUpperCase()
  return shifts.some(
    (s) =>
      s.shiftId !== ignoreShiftId &&
      s.companyId === data.companyId &&
      s.code === code,
  )
}

/** Create a shift. Returns the created shift, or { errors } on invalid input. */
export function mockCreateShift(data) {
  const errors = validateShift(data)
  if (Object.keys(errors).length > 0) return { errors }
  const shifts = readShifts()
  if (isDuplicateCode(shifts, data)) {
    return { errors: { code: 'Another shift in this company already uses this code.' } }
  }
  const shift = {
    ...data,
    shiftId: generateShiftId(data.name),
    name: data.name.trim(),
    code: data.code.trim().toUpperCase(),
    graceMinutes: Number(data.graceMinutes),
    expectedHours: Number(data.expectedHours),
    status: data.status ?? 'active',
  }
  shifts.push(shift)
  writeShifts(shifts)
  recordAuditEvent({ action: 'Shift created', category: 'Shifts & Shops', source: 'Shifts & Working Hours', actor: auditActor(), companyIds: [shift.companyId], affected: `${shift.name} (${shift.code})`, description: `${shift.startTime}–${shift.endTime}, ${formatWorkingDays(shift.workingDays)}.`, next: { name: shift.name, code: shift.code, hours: `${shift.startTime}–${shift.endTime}`, status: shift.status } })
  return { shift }
}

/** Update a shift. Returns the updated shift, or { errors } on invalid input. */
export function mockUpdateShift(shiftId, data) {
  const errors = validateShift(data)
  if (Object.keys(errors).length > 0) return { errors }
  const shifts = readShifts()
  const index = shifts.findIndex((s) => s.shiftId === shiftId)
  if (index === -1) return { errors: { name: 'Shift not found.' } }
  if (isDuplicateCode(shifts, data, shiftId)) {
    return { errors: { code: 'Another shift in this company already uses this code.' } }
  }
  const before = shifts[index]
  shifts[index] = {
    ...shifts[index],
    ...data,
    name: data.name.trim(),
    code: data.code.trim().toUpperCase(),
    graceMinutes: Number(data.graceMinutes),
    expectedHours: Number(data.expectedHours),
  }
  writeShifts(shifts)
  const after = shifts[index]
  const fields = ['name', 'code', 'startTime', 'endTime', 'workingDays', 'breakStart', 'breakEnd', 'graceMinutes', 'expectedHours', 'status', 'description']
  const changed = fields.filter((f) => JSON.stringify(before[f]) !== JSON.stringify(after[f]))
  if (changed.length) {
    recordAuditEvent({
      action: changed.length === 1 && changed[0] === 'status' ? `Shift ${after.status === 'active' ? 'activated' : 'deactivated'}` : 'Shift edited',
      category: 'Shifts & Shops',
      source: 'Shifts & Working Hours',
      actor: auditActor(),
      companyIds: [after.companyId],
      affected: `${after.name} (${after.code})`,
      description: `Changed: ${changed.join(', ')}.`,
      previous: Object.fromEntries(changed.map((f) => [f, before[f] ?? null])),
      next: Object.fromEntries(changed.map((f) => [f, after[f] ?? null])),
    })
  }
  return { shift: shifts[index] }
}
