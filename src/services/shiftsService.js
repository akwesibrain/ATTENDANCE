const TIME_PATTERN = /^([01]?\d|2[0-3]):[0-5]\d$/

/**
 * Validate a shift definition. Returns a map of field -> error message.
 * Prevents invalid time configurations.
 */
export function validateShift(data) {
  const errors = {}
  if (!data.name?.trim()) errors.name = 'Shift name is required.'
  if (!data.code?.trim()) errors.code = 'Shift code is required.'
  if (!data.companyId) errors.companyId = 'Company is required.'
  if (!TIME_PATTERN.test(data.startTime ?? '')) errors.startTime = 'Enter a valid start time (HH:MM).'
  if (!TIME_PATTERN.test(data.endTime ?? '')) errors.endTime = 'Enter a valid end time (HH:MM).'
  if (!Array.isArray(data.workingDays) || data.workingDays.length === 0) {
    errors.workingDays = 'Choose at least one working day.'
  }
  if (data.breakStart && !TIME_PATTERN.test(data.breakStart)) errors.breakStart = 'Enter a valid break start (HH:MM).'
  if (data.breakEnd && !TIME_PATTERN.test(data.breakEnd)) errors.breakEnd = 'Enter a valid break end (HH:MM).'
  if (
    data.breakStart &&
    data.breakEnd &&
    TIME_PATTERN.test(data.breakStart) &&
    TIME_PATTERN.test(data.breakEnd) &&
    timeToMinutes(data.breakEnd) <= timeToMinutes(data.breakStart)
  ) {
    errors.breakEnd = 'Break end must be after break start.'
  }
  if (data.status && !['active', 'inactive'].includes(data.status)) {
    errors.status = 'Status must be active or inactive.'
  }
  const grace = Number(data.graceMinutes)
  if (data.graceMinutes === '' || Number.isNaN(grace) || grace < 0 || grace > 120) {
    errors.graceMinutes = 'Grace period must be 0 to 120 minutes.'
  }
  const hours = Number(data.expectedHours)
  if (data.expectedHours === '' || Number.isNaN(hours) || hours <= 0 || hours > 24) {
    errors.expectedHours = 'Expected hours must be between 0 and 24.'
  }
  return errors
}

export function isShiftValid(data) {
  return Object.keys(validateShift(data)).length === 0
}

